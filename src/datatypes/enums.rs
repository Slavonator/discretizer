/// Масштабирование, если размер выходного буфера и вьюпорта не соответствуют
#[derive(Copy, Clone, Debug, PartialEq)]
pub enum ScalingMode {
    /// Растянуть до размеров порта, игнорируя пропорции
    Stretch,
    /// Вписать в порт с сохранением пропорций, пустые места остаются незанятыми
    Contain,
    /// Заполнить весь порт с сохранением пропорций, обрезая выступающие части
    Cover,
    /// Не масштабировать, координаты 1:1
    None,
}